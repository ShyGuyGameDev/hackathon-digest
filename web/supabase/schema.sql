-- WARNING: This schema is for context only and is not meant to be run.
-- Table order and constraints may not be valid for execution.

CREATE TABLE public.events (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  organizer text,
  summary text,
  description text,
  website_url text,
  registration_url text,
  rules_url text,
  start_at timestamp with time zone,
  end_at timestamp with time zone,
  timezone text,
  registration_deadline_at timestamp with time zone,
  registration_deadline_status text NOT NULL DEFAULT 'unverified'::text CHECK (registration_deadline_status = ANY (ARRAY['verified'::text, 'unverified'::text])),
  submission_deadline_at timestamp with time zone,
  submission_deadline_status text NOT NULL DEFAULT 'unverified'::text CHECK (submission_deadline_status = ANY (ARRAY['verified'::text, 'unverified'::text])),
  submission_deadline_source text,
  format text NOT NULL CHECK (format = ANY (ARRAY['online'::text, 'in_person'::text, 'hybrid'::text])),
  venue text,
  city text,
  state text,
  country text,
  country_code text,
  region text,
  latitude double precision,
  longitude double precision,
  team_min integer,
  team_max integer,
  solo_allowed boolean,
  categories jsonb NOT NULL DEFAULT '[]'::jsonb,
  technologies jsonb NOT NULL DEFAULT '[]'::jsonb,
  perks jsonb NOT NULL DEFAULT '[]'::jsonb,
  cost text CHECK (cost = ANY (ARRAY['free'::text, 'paid'::text])),
  theme text,
  deliverables text,
  judging_criteria text,
  prize_summary text,
  prizes jsonb,
  schedule jsonb,
  logo_url text,
  dedupe_key text NOT NULL,
  website_host text,
  hidden boolean NOT NULL DEFAULT false,
  is_mock boolean NOT NULL DEFAULT false,
  first_seen_at timestamp with time zone NOT NULL DEFAULT now(),
  last_verified_at timestamp with time zone,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT events_pkey PRIMARY KEY (id)
);
CREATE TABLE public.eligibility (
  event_id uuid NOT NULL,
  status text NOT NULL CHECK (status = ANY (ARRAY['verified'::text, 'unclear'::text, 'ineligible'::text])),
  high_school_allowed boolean,
  education_levels jsonb NOT NULL DEFAULT '[]'::jsonb,
  min_age integer,
  max_age integer,
  grades jsonb NOT NULL DEFAULT '[]'::jsonb,
  geographic_restrictions text,
  international_allowed boolean,
  requires_college_enrollment boolean,
  method text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '[]'::jsonb,
  source_url text,
  content_hash text,
  checked_at timestamp with time zone NOT NULL DEFAULT now(),
  notes text,
  manual boolean NOT NULL DEFAULT false,
  needs_review boolean NOT NULL DEFAULT false,
  CONSTRAINT eligibility_pkey PRIMARY KEY (event_id),
  CONSTRAINT eligibility_event_id_fkey FOREIGN KEY (event_id) REFERENCES public.events(id)
);
CREATE TABLE public.event_sources (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  event_id uuid NOT NULL,
  source text NOT NULL,
  external_id text NOT NULL,
  source_url text,
  normalized jsonb NOT NULL,
  raw jsonb,
  first_seen_at timestamp with time zone NOT NULL DEFAULT now(),
  last_seen_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT event_sources_pkey PRIMARY KEY (id),
  CONSTRAINT event_sources_event_id_fkey FOREIGN KEY (event_id) REFERENCES public.events(id)
);
CREATE TABLE public.event_overrides (
  event_id uuid NOT NULL,
  field text NOT NULL,
  value jsonb NOT NULL,
  note text,
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT event_overrides_pkey PRIMARY KEY (event_id, field),
  CONSTRAINT event_overrides_event_id_fkey FOREIGN KEY (event_id) REFERENCES public.events(id)
);
CREATE TABLE public.ingestion_runs (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  source text NOT NULL,
  started_at timestamp with time zone NOT NULL DEFAULT now(),
  finished_at timestamp with time zone,
  status text NOT NULL CHECK (status = ANY (ARRAY['running'::text, 'succeeded'::text, 'failed'::text])),
  stats jsonb,
  error text,
  CONSTRAINT ingestion_runs_pkey PRIMARY KEY (id)
);
CREATE TABLE public.submissions (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'pending'::text CHECK (status = ANY (ARRAY['pending'::text, 'approved'::text, 'rejected'::text])),
  payload jsonb NOT NULL,
  contact_email text,
  review_note text,
  reviewed_at timestamp with time zone,
  event_id uuid,
  CONSTRAINT submissions_pkey PRIMARY KEY (id),
  CONSTRAINT submissions_event_id_fkey FOREIGN KEY (event_id) REFERENCES public.events(id)
);